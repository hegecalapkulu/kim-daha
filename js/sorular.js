/* ---------- PAKETLER: 9 ayrık paket, kategoriler eşit dağıtılır ----------
   Her kategorinin 22 sorusu 9 pakete sırayla dağıtılır (her pakete 2-3 soru).
   Kategoriye göre kaydırma (×4) sayesinde fazladan 3. sorular da paketlere eşit düşer:
   baharatsız her paket tam 44 soru. Baharatlı sorular ayrıca 2-3'er dağıtılır.
   Bir soru yalnızca tek bir pakette bulunur. */
window.PAKETLER = [
  { ad: 'Isınma Turu', e: '🔥' }, { ad: 'Kahve Molası', e: '☕' }, { ad: 'Gece Yarısı', e: '🌙' },
  { ad: 'Yol Arkadaşı', e: '🚗' }, { ad: 'Kantin Masası', e: '🥪' }, { ad: 'Doğum Günü', e: '🎂' },
  { ad: 'Tatil Dönüşü', e: '🏖️' }, { ad: 'Ev Partisi', e: '🎉' }, { ad: 'Son Durak', e: '🚏' },
];
window.paketSorulari = function (pi, { baharat = false } = {}) {
  const N = PAKETLER.length, out = [];
  Object.keys(SORULAR).forEach((kat, ci) => {
    if (kat === 'baharatli' && !baharat) return;
    const off = kat === 'baharatli' ? 0 : (ci * 4) % N;
    SORULAR[kat].forEach((soru, j) => { if ((j + off) % N === pi) out.push({ kat, soru }); });
  });
  return out;
};
